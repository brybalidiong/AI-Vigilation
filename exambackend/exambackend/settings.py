def _postgres_options() -> dict:
    options = {
        'connect_timeout': int(os.getenv('DB_CONNECT_TIMEOUT', '15')),
        'sslmode': os.getenv('DB_SSLMODE', 'require'),
    }
    hostaddr = os.getenv('DB_HOSTADDR', '').strip()
    if hostaddr:
        options['hostaddr'] = hostaddr
    return options


def _database_from_url(url: str) -> dict:
    """Parse Supabase/Postgres URI from dashboard (Session or Transaction pooler)."""
    parsed = urlparse(url)
    if parsed.scheme not in ('postgresql', 'postgres'):
        raise ValueError(f'Unsupported DATABASE_URL scheme: {parsed.scheme}')
    query = parse_qs(parsed.query)
    options = _postgres_options()
    options['sslmode'] = (query.get('sslmode') or [options['sslmode']])[0]
    if 'connect_timeout' in query:
        options['connect_timeout'] = int(query['connect_timeout'][0])
    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': (parsed.path or '/postgres').lstrip('/') or 'postgres',
        'USER': unquote(parsed.username or ''),
        'PASSWORD': unquote(parsed.password or ''),
        'HOST': parsed.hostname or '',
        'PORT': parsed.port or 5432,
        'CONN_MAX_AGE': 0,
        'OPTIONS': options,
    }


